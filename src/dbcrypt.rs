use crate::aes::{cfb_decrypt, cfb_encrypt};

const PART_A: [u8; 16] = [
    0x4d, 0x1a, 0x8e, 0x63, 0xf0, 0x27, 0x9b, 0x55, 0xc2, 0x3d, 0x71, 0xae, 0x08, 0x94, 0x6c, 0xb3,
];
const PART_B: [u8; 16] = [
    0x92, 0xf7, 0x11, 0xd4, 0x88, 0x5c, 0x03, 0x6a, 0xe9, 0x24, 0xbb, 0x50, 0xd7, 0x1e, 0x99, 0x46,
];

fn key() -> [u8; 16] {
    let mut k = [0u8; 16];
    for i in 0..16 {
        k[i] = PART_A[i] ^ PART_B[i];
    }
    k
}

pub fn encrypt(data: &mut [u8]) {
    cfb_encrypt(&key(), data);
}

pub fn decrypt(data: &mut [u8]) {
    cfb_decrypt(&key(), data);
}
